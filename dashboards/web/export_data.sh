#!/usr/bin/env bash
# Exports the warehouse figures used by the web dashboard to
# dashboards/web/assets/dashboard-data.js. Needs the warehouse container
# running with a complete pipeline run (make up, then make all).
#
#   bash dashboards/web/export_data.sh      (or: make web-data)
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
out="$here/assets/dashboard-data.js"
cd "$here/../.."

{
    printf '// Generated by dashboards/web/export_data.sh from the warehouse. Do not edit.\n'
    printf 'window.DASHBOARD_DATA = '
    docker compose exec -T warehouse psql -U warehouse -d warehouse -At -v ON_ERROR_STOP=1 < "$here/export_data.sql" | tr -d '\r'
    printf ';\n'
} > "$out.tmp"
mv "$out.tmp" "$out"

echo "Wrote $out ($(wc -c < "$out") bytes)"
